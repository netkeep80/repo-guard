import assert from "node:assert/strict";
import * as documentFacts from "../dist/markdown-structure.mjs";

const requiredApi = [
  "resolveMarkdownAnchor",
  "listMarkdownAnchorIds",
  "readMarkdownNode",
  "listMarkdownChildren",
  "insertMarkdownChild",
  "readOwnedMarkdownBlock",
  "replaceOwnedMarkdownBlock",
];

for (const name of requiredApi) {
  assert.equal(
    typeof documentFacts[name],
    "function",
    `MDDB RED: current document-facts lacks ${name}`,
  );
}

const {
  resolveMarkdownAnchor,
  listMarkdownAnchorIds,
  readMarkdownNode,
  listMarkdownChildren,
  insertMarkdownChild,
  readOwnedMarkdownBlock,
  replaceOwnedMarkdownBlock,
} = documentFacts;

const addressDocument = [
  "# Document",
  '<a id="root-address"></a>',
  "Authored root text.",
  "",
  "## Addressed section",
  '<a id="section-address"></a>',
  "Authored section payload.",
  "",
  "~~~html",
  '<a id="fake-address"></a>',
  "~~~",
].join("\n");

assert.deepEqual(
  resolveMarkdownAnchor(addressDocument, "section-address").headingPath.map((x) => [x.level, x.text]),
  [[1, "Document"], [2, "Addressed section"]],
  "a stable anchor is an address even when it is not a canonical tree node",
);
assert.deepEqual(
  listMarkdownAnchorIds(addressDocument),
  ["root-address", "section-address"],
  "anchors inside fenced code are not structural addresses",
);
assert.throws(
  () => readMarkdownNode(addressDocument, "section-address"),
  /canonical tree node/,
  "address identity must remain distinct from stricter node identity",
);
assert.throws(
  () => resolveMarkdownAnchor(addressDocument + '\n<a id="section-address"></a>\n', "section-address"),
  /duplicated/,
  "duplicate stable anchors fail closed",
);

const treeDocument = [
  '<a id="db-root"></a>',
  "# Root",
  "Root payload.",
  "",
  '<a id="db-a"></a>',
  "## Node A",
  "Authored A.",
  "",
  '<a id="db-a1"></a>',
  "### Node A1",
  "Authored A1.",
  "",
  '<a id="db-b"></a>',
  "## Node B",
  "Authored B.",
  "",
  "```md",
  '<a id="db-fake"></a>',
  "## Fake node",
  "```",
].join("\n");

const rootNode = readMarkdownNode(treeDocument, "db-root");
const nodeA = readMarkdownNode(treeDocument, "db-a");
assert.equal(rootNode.end, treeDocument.length);
assert.deepEqual(
  nodeA.headingPath.map((x) => [x.level, x.text]),
  [[1, "Root"], [2, "Node A"]],
);
assert.deepEqual(listMarkdownChildren(treeDocument, "db-root").map((x) => x.anchorId), ["db-a", "db-b"]);
assert.deepEqual(listMarkdownChildren(treeDocument, "db-a").map((x) => x.anchorId), ["db-a1"]);
assert.ok(!nodeA.subtree.includes('<a id="db-b"></a>'));

const withChild = insertMarkdownChild({
  source: treeDocument,
  mode: "hybrid",
  parentAnchorId: "db-a",
  child: {
    anchorId: "db-a2",
    title: "Node A2",
    payload: "Generated child payload.",
  },
});
assert.deepEqual(listMarkdownChildren(withChild, "db-a").map((x) => x.anchorId), ["db-a1", "db-a2"]);
assert.ok(withChild.indexOf('<a id="db-a2"></a>') < withChild.indexOf('<a id="db-b"></a>'));
assert.equal(
  withChild.slice(withChild.indexOf('<a id="db-b"></a>')),
  treeDocument.slice(treeDocument.indexOf('<a id="db-b"></a>')),
  "insertChild must preserve every byte after the addressed insertion boundary",
);
assert.throws(
  () => insertMarkdownChild({
    source: treeDocument,
    mode: "source",
    parentAnchorId: "db-root",
    child: { anchorId: "blocked", title: "Blocked" },
  }),
  /read-only/,
);
assert.throws(
  () => insertMarkdownChild({
    source: treeDocument,
    mode: "hybrid",
    parentAnchorId: "db-root",
    child: { anchorId: "hidden", title: "Hidden", payload: "## hidden subtree" },
  }),
  /payload/,
);

const begin = "<!-- consumer:owned:summary:begin -->";
const end = "<!-- consumer:owned:summary:end -->";
const ownedSource = [
  '<a id="hybrid-node"></a>',
  "# Hybrid node",
  "Authored before.",
  begin,
  "old generated bytes",
  end,
  "Authored after.",
].join("\n");

const existing = readOwnedMarkdownBlock(ownedSource, { blockId: "summary", beginMarker: begin, endMarker: end });
assert.match(existing?.content ?? "", /old generated bytes/);

const replaced = replaceOwnedMarkdownBlock({
  source: ownedSource,
  mode: "hybrid",
  anchorId: "hybrid-node",
  block: { blockId: "summary", beginMarker: begin, endMarker: end },
  generatedContent: "new generated bytes",
});
assert.ok(replaced.includes("Authored before."));
assert.ok(replaced.includes("Authored after."));
assert.match(replaced, /new generated bytes/);
assert.equal(
  replaceOwnedMarkdownBlock({
    source: replaced,
    mode: "hybrid",
    anchorId: "hybrid-node",
    block: { blockId: "summary", beginMarker: begin, endMarker: end },
    generatedContent: "new generated bytes",
  }),
  replaced,
  "owned-block replacement is deterministic/idempotent",
);

assert.throws(
  () => readOwnedMarkdownBlock(
    ownedSource.replace(end, ""),
    { blockId: "summary", beginMarker: begin, endMarker: end },
  ),
  /malformed owned block/,
  "malformed ownership markers fail closed",
);

console.log("MDDB structural model falsifier passed.");
